// src/ui/components/shareMenu.js
//
// The top-bar share button and the menu behind it. Same glyph, same
// button placement (immediately left of the Settings gear) and the same
// .share-menu-* classes as Corn Plot Harvest's own share menu, so a rep
// who uses that app finds this one without looking.
//
// Three actions, and the split between them is deliberate:
//
//   Print / Save as PDF — the one that produces a real artifact. Every
//     phone and desktop browser's print dialog can save to PDF, which
//     is what actually gets emailed or texted to a customer. The heavy
//     lifting is in the @media print block in gdu.css.
//
//   Share…             — the OS share sheet via navigator.share, on the
//     devices that have it. Sends a text summary, NOT a link to this
//     specific result — see the note on buildSummary() below for why.
//
//   Copy summary       — the fallback that works everywhere, including
//     desktop browsers with no share sheet.
//
// Share… is hidden entirely when navigator.share is missing rather than
// shown-and-broken; Copy summary covers that case.

import { h, clear, debounceGuard } from "../dom.js";
import { showCustomModal } from "./modal.js";
import { showToast } from "./toast.js";
import { formatShort } from "../../core/dates.js";

// The classic box-with-up-arrow share glyph, matching Corn Plot
// Harvest's. stroke="currentColor" so it tracks the top bar's white
// icons in both themes.
const SHARE_ICON_SVG = `
<svg viewBox="0 0 24 24" width="20" height="20" fill="none" stroke="currentColor" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">
  <path d="M12 3 L12 14" />
  <path d="M8 6.5 L12 3 L16 6.5" />
  <path d="M7 10 H5 V21 H19 V10 H17" />
</svg>
`.trim();

/**
 * A plain-text recap of the result, for the share sheet and the
 * clipboard.
 *
 * NOTE what this deliberately does NOT do: attach a link that reproduces
 * this calculation. Results are derived from inputs held in this
 * device's own local storage, so a URL would open the app on the
 * recipient's phone showing THEIR last calculation, not this one — which
 * is worse than sending no link at all, because it looks like it worked.
 * The text carries the numbers; Print / Save as PDF carries the charts.
 *
 * @param {Object} args
 * @returns {string}
 */
export function buildSummary({ season, hybrid, location, rows }) {
  const lines = [];
  lines.push(`GDU outlook — ${hybrid.label}`);
  lines.push(`${location.label} · planted ${formatShort(season.plantingIso, { withYear: true })}`);

  const est = [];
  if (hybrid.silk && hybrid.silk.source !== "entered") est.push("silk");
  if (hybrid.blackLayer && hybrid.blackLayer.source !== "entered") est.push("black layer");
  lines.push(
    `Rated ${hybrid.gduToSilk.toLocaleString()} GDU to silk, ${hybrid.gduToBlackLayer.toLocaleString()} to black layer` +
      (est.length ? ` (${est.join(" and ")} estimated, not from a tech sheet)` : "")
  );

  if (season.gduToDate !== null && season.gduToDate !== undefined) {
    const vs = season.gduVsNormal;
    lines.push(
      `\n${Math.round(season.gduToDate).toLocaleString()} GDU through ${formatShort(season.lastObservedIso, { withYear: true })}` +
        (vs === null ? "" : `, ${Math.abs(Math.round(vs)).toLocaleString()} ${vs >= 0 ? "ahead of" : "behind"} normal`)
    );
  }

  lines.push("\nPredicted dates:");
  for (const row of rows) {
    const silk = row.silkIso ? formatShort(row.silkIso, { withYear: true }) : "not reached";
    const bl = row.blackLayerIso ? formatShort(row.blackLayerIso, { withYear: true }) : "not reached";
    lines.push(`  ${row.label}: silk ${silk}, black layer ${bl}`);
  }

  if (season.killingFreeze && season.killingFreeze.medianMonthDay) {
    lines.push(
      `\nMedian first 28 °F freeze ${formatShort(`${season.plantingYear}-${season.killingFreeze.medianMonthDay}`)}; 1 year in 10 by ${formatShort(
        `${season.plantingYear}-${season.killingFreeze.p10MonthDay}`
      )}.`
    );
  }

  lines.push("\nGDU is a heat model — it knows nothing about drought, replant, hail or disease.");
  lines.push("Generated by the GDU Calculator.");
  return lines.join("\n");
}

/**
 * Builds the top-bar share button. Returns the button element, ready to
 * hand to createTopBar's `right` slot (which places it left of the gear).
 * @param {() => Object} getContext supplies the current season/hybrid/etc
 *   at click time, so the menu can't capture stale data from a render
 *   that happened before the weather finished loading.
 * @returns {HTMLElement}
 */
export function createShareButton(getContext) {
  return h(
    "button",
    {
      type: "button",
      className: "top-bar-btn top-bar-btn-share",
      "aria-label": "Share or print",
      onclick: debounceGuard(() => openShareMenu(getContext())),
    },
    h("span", { className: "top-bar-share-icon", html: SHARE_ICON_SVG })
  );
}

function openShareMenu(ctx) {
  if (!ctx) {
    showToast("Nothing to share yet — the results are still loading.", { type: "error" });
    return;
  }

  const panel = h("div", { className: "share-menu-panel share-menu-panel-modal" });
  const modal = showCustomModal({ title: "Share This Outlook", bodyNode: panel });

  const items = [];

  items.push([
    "Print / Save as PDF",
    "Opens your browser's print dialog. Choose “Save as PDF” to get a file you can email or text.",
    () => {
      modal.close();
      // The dialog is modal and synchronous in most browsers; letting the
      // overlay finish tearing down first keeps it out of the printed
      // page in the ones where it isn't.
      setTimeout(() => window.print(), 120);
    },
  ]);

  const summary = () => buildSummary(ctx);

  if (typeof navigator !== "undefined" && navigator.share) {
    items.push([
      "Share…",
      "Sends the numbers as text through your phone's share sheet.",
      async () => {
        modal.close();
        try {
          await navigator.share({ title: `GDU outlook — ${ctx.hybrid.label}`, text: summary() });
        } catch (e) {
          // AbortError just means the user dismissed the sheet — not a
          // failure worth a toast.
          if (e && e.name !== "AbortError") showToast("Couldn't open the share sheet.", { type: "error" });
        }
      },
    ]);
  }

  items.push([
    "Copy summary",
    "Puts the numbers on the clipboard as plain text.",
    async () => {
      modal.close();
      const text = summary();
      try {
        await navigator.clipboard.writeText(text);
        showToast("Summary copied.", { type: "success", duration: 2500 });
      } catch (e) {
        // Clipboard API needs a secure context and a user gesture; on the
        // browsers where it's blocked, fall back to a selectable textarea
        // rather than telling someone their copy failed with no recourse.
        fallbackCopy(text);
      }
    },
  ]);

  clear(panel);
  for (const [label, hint, onClick] of items) {
    panel.appendChild(
      h("button", { type: "button", className: "share-menu-item", onclick: debounceGuard(onClick) }, [
        h("span", { className: "share-menu-item-label" }, label),
        h("span", { className: "share-menu-item-hint" }, hint),
      ])
    );
  }
}

/** Last-resort copy: show the text selected so it can be copied by hand. */
function fallbackCopy(text) {
  const area = h("textarea", { className: "text-input text-area gdu-copy-fallback", readonly: true }, text);
  showCustomModal({
    title: "Copy Summary",
    bodyNode: h("div", { className: "search-list-body" }, [h("p", { className: "field-note" }, "Your browser blocked the clipboard. Select this text and copy it."), area]),
  });
  setTimeout(() => {
    area.focus();
    area.select();
  }, 0);
}
